"""Monta o Dino de ponta a ponta.

1. Gera as imagens PNG (tools/make_assets.py)
2. Converte as imagens para o formato da SDRAM e cria dino_assets.h
3. Compila o C para RV32I com o GCC do servidor
4. Escreve:
   - dist/examples/dino.json   (projeto que aparece no seletor do Studio)
   - examples/dino/dino.json.prog (pacote para o loader da FPGA)
   - Riscplay_Player.html      (player offline, com o Dino incluido)

Uso:  python examples/dino/build.py
"""
import base64, json, shutil, sys, uuid
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(HERE / 'tools'))
import server              # noqa: E402
import make_assets         # noqa: E402

# Ordem fixa = enderecos estaveis na SDRAM.
ASSETS = ['dino_stand', 'dino_run1', 'dino_run2', 'dino_dead', 'dino_duck1', 'dino_duck2',
          'cactus_s1', 'cactus_s2', 'cactus_l1', 'cactus_l3', 'ptero1', 'ptero2',
          'cloud', 'ground', 'restart', 'digits',
          'txt_hi', 'txt_gameover', 'txt_title', 'txt_press']
# Logo apos os framebuffers (0xA080 e 0x18180, 320x180 palavras cada).
SDRAM_BASE = 0x26280
SOURCES = ['main.c', 'dino_assets.h', 'console.h', 'riscplay_audio.h', 'riscplay_audio.c']


def main():
    make_assets.build(HERE / 'assets')

    images = [{'name': n + '.png',
               'data': base64.b64encode((HERE / 'assets' / (n + '.png')).read_bytes()).decode()}
              for n in ASSETS]
    conv = server.convert_images({'images': images, 'base': SDRAM_BASE})
    header = conv['header'].replace('RISCPLAY_ASSETS_H', 'DINO_ASSETS_H')
    header = header.replace('/* Generated by RiscPlay Asset Manager;',
                            '/* Gerado por examples/dino/build.py. Nao edite a mao;')
    (HERE / 'dino_assets.h').write_text(header, encoding='utf-8', newline='\n')
    last = conv['entries'][-1]
    print('Assets: %d imagens, SDRAM 0x%X-0x%X'
          % (len(ASSETS), SDRAM_BASE, last['palette_addr'] + last['words']))

    # Bibliotecas do SDK copiadas para o projeto (como no FlappyBird).
    for name in ['console.h', 'riscplay_audio.h', 'riscplay_audio.c']:
        shutil.copy2(ROOT / 'sdk' / name, HERE / name)

    files = {n: (HERE / n).read_text(encoding='utf-8') for n in SOURCES}
    result = server.compile_files(files, server.find_compiler())
    if not result['ok']:
        print(result['error'])
        sys.exit(1)
    if result['log'].strip():
        print(result['log'])
    print('Firmware: %d bytes (limite 28672)' % result['size'])

    firmware = {'comp_uuid': str(uuid.uuid5(uuid.NAMESPACE_URL, 'riscplay-studio/dino/firmware')),
                'type': 0, 'addr': '20000000', 'addr_mem': '20000000', 'value': result['hex']}
    package = [firmware, *conv['blocks']]

    example = {'id': 'dino', 'title': 'Dino', 'files': files, 'package': package}
    (ROOT / 'dist/examples/dino.json').write_text(json.dumps(example), encoding='utf-8')
    (HERE / 'dino.json.prog').write_text(json.dumps(package), encoding='utf-8')

    index_path = ROOT / 'dist/examples/index.json'
    index = json.loads(index_path.read_text(encoding='utf-8'))
    if not any(e['id'] == 'dino' for e in index):
        index.insert(0, {'id': 'dino', 'title': 'Dino'})
        index_path.write_text(json.dumps(index), encoding='utf-8')

    import runpy
    runpy.run_path(str(ROOT / 'build_player.py'))
    print('Pronto: selecione "Dino" no Studio ou abra Riscplay_Player.html.')


if __name__ == '__main__':
    main()
