"""RiscPlay SDRAM asset conversion: 256 RGB words + packed 8-bit indices (MSB-first).
Addresses are SDRAM *word* addresses, matching console.h and sprites.h.
"""
from __future__ import annotations
import io, re, struct
from PIL import Image

SDRAM_WORDS = 0x200000
DEFAULT_BASE = 0x35000  # After sample Flappy Bird assets (last ~0x339a8)

def convert(images, base=DEFAULT_BASE, max_colors=256):
    if not isinstance(images, list) or not images or len(images)>128:
        raise ValueError('Supply 1..128 images')
    if not (0<=base<SDRAM_WORDS) or not (2<=max_colors<=256):
        raise ValueError('Invalid base address or color limit')
    writes=[]; entries=[]; used=set(); cursor=base
    for spec in images:
        name=spec['name']; raw=spec['data']
        key=re.sub(r'[^A-Za-z0-9_]','_',name.rsplit('.',1)[0]).upper()
        if not key or key[0].isdigit(): key='ASSET_'+key
        if key in used: raise ValueError('Duplicate asset name: '+key)
        used.add(key)
        im=Image.open(io.BytesIO(raw)); im.load()
        if im.format != 'PNG':
            raise ValueError('Only PNG images are supported: '+name)
        if not (1 <= im.width <= 127 and 1 <= im.height <= 127):
            raise ValueError('Sprite %s is %dx%d; maximum is 127x127' % (name,im.width,im.height))
        # Transparency is determined exclusively by the PNG's native alpha.
        # Fully opaque PNGs remain fully opaque. Existing 255 sentinel is preserved.
        rgba=im.convert('RGBA')
        pix=list(rgba.getdata())
        masked=[p[3]<128 for p in pix]
        transparent_pixels=sum(masked)
        tr=None
        visible=[p[:3] for p,m in zip(pix,masked) if not m]
        unique=list(dict.fromkeys(visible))
        limit=max_colors-1
        if len(unique)<=limit:
            colors=unique
            indices={c:i for i,c in enumerate(colors)}
            pixel_ids=[limit if m else indices[p[:3]] for p,m in zip(pix,masked)]
        else:
            # Median-cut quantization without dithering; preserve transparency mask.
            rgb=Image.new('RGB', im.size)
            rgb.putdata([p[:3] for p in pix])
            quant=rgb.quantize(colors=limit, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE)
            qpal=quant.getpalette(); qids=list(quant.getdata())
            active=sorted({idx for idx,m in zip(qids,masked) if not m})
            remap={v:i for i,v in enumerate(active)}
            colors=[tuple(qpal[v*3:v*3+3]) for v in active]
            pixel_ids=[limit if m else remap[idx] for idx,m in zip(qids,masked)]
        # Transparent RGB remains the last effective palette entry; the PPU uses pixel index 255 as its transparency sentinel.
        transparent_index=len(colors)
        pixel_ids=[255 if m else v for v,m in zip(pixel_ids,masked)]
        if tr is None: tr=(255,0,255)
        palette=colors+[tr]
        if len(palette)>256: raise ValueError('Palette overflow')
        palette_words=[(r<<16)|(g<<8)|b for r,g,b in palette]
        palette_words += [0]*(256-len(palette))
        # RTL STATE_SDRAM_TO_BUFFER_P3 reads bytes [31:24], [23:16], [15:8], [7:0].
        pixel_words=[]
        for i in range(0,len(pixel_ids),4):
            a=pixel_ids[i:i+4]+[0]*max(0,4-len(pixel_ids[i:i+4]))
            pixel_words.append((a[0]<<24)|(a[1]<<16)|(a[2]<<8)|a[3])
        # Reserve 256 palette words then pixel data; header ADDR points at pixels.
        pal_addr=cursor; pix_addr=cursor+256
        if pix_addr+len(pixel_words)>SDRAM_WORDS: raise ValueError('SDRAM capacity exceeded')
        writes.extend((pal_addr+i,v) for i,v in enumerate(palette_words))
        writes.extend((pix_addr+i,v) for i,v in enumerate(pixel_words))
        entries.append(dict(name=key,width=im.width,height=im.height,palette_addr=pal_addr,pixels_addr=pix_addr,colors=len(palette),transparent_index=transparent_index,transparent_pixel_index=255,transparent_pixels=transparent_pixels,words=256+len(pixel_words)))
        cursor=pix_addr+len(pixel_words)
    binary=b''.join(struct.pack('<II',addr,val) for addr,val in writes)
    lines=['/* Generated by RiscPlay Asset Manager; SDRAM addresses are 32-bit words. */','#ifndef RISCPLAY_ASSETS_H','#define RISCPLAY_ASSETS_H','']
    for e in entries:
        k=e['name']; lines.extend([f'#define {k}_ADDR 0x{e["pixels_addr"]:X}u',f'#define {k}_PALETTE_ADDR 0x{e["palette_addr"]:X}u',f'#define {k}_WIDTH {e["width"]}u',f'#define {k}_HEIGHT {e["height"]}u',f'#define {k}_COLORS {e["colors"]}u',f'#define {k}_TRANSPARENT_INDEX 255u',f'#define {k}_TRANSPARENT_PALETTE_INDEX {e["transparent_index"]}u',''])
    lines+=['#endif','']
    return binary,'\n'.join(lines),entries
